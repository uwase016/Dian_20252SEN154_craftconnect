CREATE TABLE ARTISAN (
    artisan_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    phone VARCHAR2(20),
    email VARCHAR2(100),
    location VARCHAR2(100)
);

CREATE TABLE CATEGORY (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(100) NOT NULL UNIQUE,
    description VARCHAR2(255)
);

CREATE TABLE PRODUCT (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artisan_id NUMBER NOT NULL,
    category_id NUMBER NOT NULL,
    product_name VARCHAR2(100) NOT NULL,
    description VARCHAR2(255),
    price NUMBER(10,2) NOT NULL,
    quantity_in_stock NUMBER DEFAULT 0 NOT NULL,
    created_at DATE DEFAULT SYSDATE,
    CONSTRAINT fk_product_artisan FOREIGN KEY (artisan_id)
        REFERENCES ARTISAN(artisan_id),
    CONSTRAINT fk_product_category FOREIGN KEY (category_id)
        REFERENCES CATEGORY(category_id),
    CONSTRAINT chk_product_price CHECK (price >= 0),
    CONSTRAINT chk_product_stock CHECK (quantity_in_stock >= 0)
);

CREATE TABLE CUSTOMER (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    phone VARCHAR2(20),
    email VARCHAR2(100),
    address VARCHAR2(200),
    created_at DATE DEFAULT SYSDATE
);

CREATE TABLE ORDERS (
    order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER NOT NULL,
    order_date DATE DEFAULT SYSDATE,
    status VARCHAR2(30) DEFAULT 'Pending',
    total_amount NUMBER(10,2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES CUSTOMER(customer_id),
    CONSTRAINT chk_orders_amount CHECK (total_amount >= 0)
);

CREATE TABLE ORDER_ITEMS (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity NUMBER NOT NULL,
    unit_price NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_orderitems_order FOREIGN KEY (order_id)
        REFERENCES ORDERS(order_id),
    CONSTRAINT fk_orderitems_product FOREIGN KEY (product_id)
        REFERENCES PRODUCT(product_id),
    CONSTRAINT chk_orderitems_quantity CHECK (quantity > 0),
    CONSTRAINT chk_orderitems_price CHECK (unit_price >= 0)
);

CREATE TABLE PAYMENT (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER NOT NULL,
    payment_date DATE DEFAULT SYSDATE,
    payment_method VARCHAR2(50),
    amount NUMBER(10,2) NOT NULL,
    payment_status VARCHAR2(30) DEFAULT 'Pending',
    CONSTRAINT fk_payment_order FOREIGN KEY (order_id)
        REFERENCES ORDERS(order_id),
    CONSTRAINT chk_payment_amount CHECK (amount >= 0)
);

CREATE TABLE STOCK_MOVEMENTS (
    movement_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER NOT NULL,
    movement_type VARCHAR2(30) NOT NULL,
    quantity NUMBER NOT NULL,
    movement_date DATE DEFAULT SYSDATE,
    notes VARCHAR2(255),
    CONSTRAINT fk_stock_product FOREIGN KEY (product_id)
        REFERENCES PRODUCT(product_id),
    CONSTRAINT chk_stock_quantity CHECK (quantity > 0),
    CONSTRAINT chk_movement_type CHECK (movement_type IN ('IN', 'OUT'))
);
